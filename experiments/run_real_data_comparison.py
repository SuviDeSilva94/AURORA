"""
Third workload: dual-gate evaluation on the AI4I 2020 Predictive Maintenance
Dataset (UCI Machine Learning Repository).

This is a real-data evaluation, parallel in role to the two synthetic
workloads in ``run_comparison.py`` (CCTV) and ``run_motor_comparison.py``
(industrial motor monitoring). It tests whether the dual-gate's behaviour
generalises from synthetic to real industrial fault telemetry.

The dataset contains 10,000 rows of industrial machine telemetry with five
documented failure modes. This evaluation uses the three dominant fault
classes that have clean single-fault rows (no concurrent failure flags):

  HDF (Heat Dissipation Failure)    n=106 trials
  PWF (Power Failure)               n=80  trials
  OSF (Overstrain Failure)          n=78  trials
  -------------------------------------------------
  total                              n=264 single-fault rows

Each row carries five continuous features (air temperature, process
temperature, rotational speed, torque, tool wear). The features are
discretised against the dataset's documented failure-mode thresholds:

  HDF: (process_temp - air_temp) < 8.6 K AND rotational_speed < 1380 rpm
  PWF: torque*rotational_speed*(2*pi/60) outside [3500, 9000] W
  OSF: tool_wear * torque > 12,000 (per machine quality variant)

A six-node Bayesian network is trained on a 1,000-row healthy sample plus
the 264 fault rows; the same three-agent comparison (Rule-Based, AIF No
Gate, AURORA) used on CCTV and motor is run against these trials. The
output JSONs match the naming convention used by motor:

  real_rule_based_results.json
  real_aif_no_gate_results.json
  real_aurora_results.json

The Pareto plot is generated by ``plot_real_data_tradeoff.py`` and lives
at ``experiments/results/real_data_tradeoff_pareto.pdf``.

This workload is part of the codebase's three-workload coverage and is
documented in the thesis Discussion as the real-data external-validity
check.
"""

