# ─── Real-data BN structure ────────────────────────────────────────────────

# Variables are discretised versions of the five continuous AI4I features.
REAL_DATA_EDGES = [
    ("temp_diff", "machine_health"),
    ("rot_speed", "machine_health"),
    ("torque", "machine_health"),
    ("tool_wear", "machine_health"),
    ("machine_health", "slo_violated"),
    ("temp_diff", "slo_violated"),
    ("rot_speed", "slo_violated"),
    ("torque", "slo_violated"),
    ("tool_wear", "slo_violated"),
]


# ─── Discretisation (thresholds derived from AI4I documentation) ──────────

def discretize_real_observation(row: Dict[str, Any]) -> Dict[str, Any]:
    """
    Map continuous AI4I telemetry to discrete BN labels.

    Thresholds follow the dataset's documented failure mode definitions:
      HDF: process_temp - air_temp < 8.6 K AND rot_speed < 1380 rpm
      PWF: torque * rot_speed * (2*pi/60) outside [3500, 9000] W
      OSF: tool_wear * torque > ~12,000 min*Nm
    """
    air = float(row.get("Air temperature [K]", 0))
    proc = float(row.get("Process temperature [K]", 0))
    rot = float(row.get("Rotational speed [rpm]", 0))
    tq = float(row.get("Torque [Nm]", 0))
    tw = float(row.get("Tool wear [min]", 0))

    out = {}
    out["temp_diff"] = "small" if (proc - air) < 8.6 else "normal"
    out["rot_speed"] = "low" if rot < 1380 else ("high" if rot > 2000 else "normal")
    out["torque"] = "low" if tq < 25 else ("high" if tq > 55 else "normal")
    out["tool_wear"] = "high" if tw > 200 else ("medium" if tw > 100 else "low")
    for k, v in row.items():
        if k in {"Air temperature [K]", "Process temperature [K]",
                 "Rotational speed [rpm]", "Torque [Nm]", "Tool wear [min]",
                 "machine_health", "UDI", "Product ID", "Type",
                 "Machine failure", "TWF", "HDF", "PWF", "OSF", "RNF",
                 "fault_label"}:
            continue
        out[k] = v
    return out


def discretize_for_training(row: Dict[str, Any]) -> Dict[str, Any]:
    """Same as inference-time discretisation but emits the latent machine_health
    label (derived from the dataset's 'Machine failure' flag) for BN training."""
    discrete = discretize_real_observation(row)
    discrete["machine_health"] = (
        "faulty" if int(row.get("Machine failure", 0)) == 1 else "healthy"
    )
    discrete["slo_violated"] = bool(int(row.get("Machine failure", 0)) == 1)
    return discrete


# ─── Load + filter the AI4I dataset ────────────────────────────────────────

def load_real_dataset() -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Returns:
        training_rows: discretised rows for BN fitting (healthy + faulty mix)
        fault_trials:  rows tagged with a single ground-truth fault class
        all_rows:      the full discretised DataFrame for reference
    """
    df = pd.read_csv(DATASET_PATH)

    # Single-fault-class filter: pick rows where exactly one of HDF, PWF, OSF is set
    fault_cols = ["TWF", "HDF", "PWF", "OSF", "RNF"]
    df["num_faults"] = df[fault_cols].sum(axis=1)

    def label_fault(r):
        if r["num_faults"] != 1:
            return None
        for f in ("HDF", "PWF", "OSF"):
            if r[f] == 1:
                return f
        return None

    df["fault_label"] = df.apply(label_fault, axis=1)

    # Build the test set: clean single-fault rows for HDF / PWF / OSF
    fault_trials = df[df["fault_label"].isin(["HDF", "PWF", "OSF"])].copy()
    # Build the training set: all healthy rows + the fault rows we care about
    healthy = df[df["Machine failure"] == 0].sample(n=1000, random_state=42)
    training_rows = pd.concat([healthy, fault_trials], ignore_index=True)

    return training_rows, fault_trials, df


# ─── Fit BN on discretised training data ───────────────────────────────────

def fit_real_data_bn(training_df: pd.DataFrame) -> EOSCModel:
    discrete_rows = [discretize_for_training(r) for _, r in training_df.iterrows()]
    bn_df = pd.DataFrame(discrete_rows)
    # Only keep BN nodes
    bn_df = bn_df[
        ["temp_diff", "rot_speed", "torque", "tool_wear",
         "machine_health", "slo_violated"]
    ]
    model = BayesianNetwork(REAL_DATA_EDGES)
    model.fit(bn_df, estimator=MaximumLikelihoodEstimator)
    learner = BayesianNetworkLearner()
    markov_blanket = learner._compute_markov_blankets(model)
    return EOSCModel(model=model, markov_blanket=markov_blanket)


