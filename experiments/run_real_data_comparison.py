# Correct action map per ground-truth fault.
# HDF accepts two recovery paths (cooling or speed change) because the fault
# is defined by the combination of low temp_diff AND low rot_speed; either
# intervention can in principle restore SLO compliance.
FAULT_TO_CORRECT_ACTIONS = {
    "HDF": {"improve_cooling", "adjust_speed"},
    "PWF": {"reduce_load"},
    "OSF": {"replace_tool"},
}


# ─── Anomaly counting for dynamic tau ──────────────────────────────────────

def count_real_anomalies(obs: Dict[str, Any]) -> int:
    n = 0
    air = float(obs.get("Air temperature [K]", 0))
    proc = float(obs.get("Process temperature [K]", 0))
    rot = float(obs.get("Rotational speed [rpm]", 0))
    tq = float(obs.get("Torque [Nm]", 0))
    tw = float(obs.get("Tool wear [min]", 0))
    if (proc - air) < 8.6: n += 1
    if rot < 1380 or rot > 2000: n += 1
    if tq < 25 or tq > 55: n += 1
    if tw > 200: n += 1
    return n


# ─── Agents ────────────────────────────────────────────────────────────────

class RealRuleBasedAgent:
    def __init__(self):
        self.agent_type = "real_rule_based"

    def process_observation(self, obs):
        if not obs.get("slo_violated"):
            return self._payload(None, None, "no_slo_violation")
        # Priority order: tool wear first (OSF), then power-related (PWF), then thermal (HDF)
        tw = float(obs.get("Tool wear [min]", 0))
        tq = float(obs.get("Torque [Nm]", 0))
        rot = float(obs.get("Rotational speed [rpm]", 0))
        air = float(obs.get("Air temperature [K]", 0))
        proc = float(obs.get("Process temperature [K]", 0))
        if tw > 200:
            return self._payload("replace_tool", "tool_wear", "none")
        if tq < 25 or tq > 55:
            return self._payload("reduce_load", "torque", "none")
        if (proc - air) < 8.6 and rot < 1380:
            return self._payload("improve_cooling", "temp_diff", "none")
        return self._payload("emergency_stop", "machine_health", "none")

    def _payload(self, action, root, reason):
        return {
            "action_taken": action, "root_cause": root,
            "abstained": action is None, "vfe": 0.0, "certainty": 1.0,
            "abstain_reason": reason,
        }

    def reset(self):
        pass


class RealAIFNoGateAgent:
    def __init__(self, eosc_model: EOSCModel):
        self.eosc_model = eosc_model
        self.rca = RootCauseAnalyzer(eosc_model)
        self.agent_type = "real_aif_no_gate"

    def process_observation(self, obs):
        if not obs.get("slo_violated"):
            return self._payload(None, None, True, 1.0, 0.0, "no_slo_violation")
        obs_bn = discretize_real_observation(obs)
        causes = self.rca.find_root_causes(
            symptom="slo_violated", symptom_value=True,
            observation=obs_bn, top_k=3,
        )
        if not causes:
            return self._payload(None, None, True, 0.0, 0.0, "no_root_causes")
        top = causes[0]
        action = tsg.candidate_action_for_root_variable(top.variable)
        return self._payload(
            action, top.variable, False,
            float(getattr(top, "posterior_prob", 0.0)), 0.0, "none"
        )

    def _payload(self, action, root, abstained, certainty, vfe, reason):
        return {
            "action_taken": action, "root_cause": root,
            "abstained": abstained, "vfe": vfe, "certainty": certainty,
            "abstain_reason": reason,
        }

    def reset(self):
        pass


def create_real_aurora_agent(
    eosc_model: EOSCModel,
    *,
    certainty_threshold: float = 0.70,
    vfe_threshold: float = 3.85,
    tau_min: float = 0.50,
    tau_lambda: float = 0.15,
):
    rca = RootCauseAnalyzer(eosc_model)
    vfe_computer = VFEComputer()
    gate = UncertaintyGate(threshold=vfe_threshold)

    class AURORAReal:
        def __init__(self):
            self.eosc_model = eosc_model
            self.rca = rca
            self.vfe_computer = vfe_computer
            self.gate = gate
            self.agent_type = "real_aurora"
            self.certainty_threshold = certainty_threshold
            self.tau_min = tau_min
            self.tau_lambda = tau_lambda
            self.vfe_threshold = vfe_threshold

        def process_observation(self, obs):
            if not obs.get("slo_violated"):
                return {
                    "action_taken": None, "root_cause": None,
                    "abstained": False, "vfe": 0.0, "certainty": 1.0,
                    "abstain_reason": "no_slo_violation",
                }
            obs_bn = discretize_real_observation(obs)
            n_anom = count_real_anomalies(obs)
            effective_tau = dynamic_tau_from_anomalies(
                n_anom, self.certainty_threshold, self.tau_min, self.tau_lambda
            )
            diag = diagnose_slo_violation(
                self.rca, obs_bn, top_k=3, impact_calibration=0.42
            )
            if not diag["root_causes"]:
                return {
                    "action_taken": None, "root_cause": None,
                    "abstained": True, "vfe": 0.0, "certainty": 0.0,
                    "abstain_reason": "no_root_causes",
                    "gate1_fired": False, "gate2_fired": False,
                }
            cert = diag["certainty"]
            top_cause = diag["top_cause"]
            action = diag["candidate_action"]
            if cert < effective_tau:
                return {
                    "action_taken": None, "root_cause": top_cause.variable,
                    "abstained": True, "vfe": 0.0, "certainty": cert,
                    "abstain_reason": "low_certainty",
                    "gate1_fired": True, "gate2_fired": False,
                }
            vfe_val = self.vfe_computer.compute_vfe(self.eosc_model, obs_bn, action)
            if not self.gate.should_act(vfe_val):
                return {
                    "action_taken": None, "root_cause": top_cause.variable,
                    "abstained": True, "vfe": vfe_val, "certainty": cert,
                    "abstain_reason": "high_vfe",
                    "gate1_fired": False, "gate2_fired": True,
                }
            return {
                "action_taken": action, "root_cause": top_cause.variable,
                "abstained": False, "vfe": vfe_val, "certainty": cert,
                "abstain_reason": "none",
                "gate1_fired": False, "gate2_fired": False,
            }

        def reset(self):
            pass

    return AURORAReal()


# ─── Classification ────────────────────────────────────────────────────────

ALL_ACTIONS = set(REAL_DATA_ACTIONS.keys())

def classify_outcome(fault_type: str, result: Dict[str, Any]) -> str:
    if result.get("abstained"):
        return "abstained"
    action = result.get("action_taken")
    if action is None:
        return "no_action"
    correct_set = FAULT_TO_CORRECT_ACTIONS[fault_type]
    if action in correct_set:
        return "correct"
    # emergency_stop on a non-machine_health fault is destructive (over-aggressive)
    if action in ALL_ACTIONS:
        return "destructive"
    return "incorrect"


# ─── F_th auto-calibration ─────────────────────────────────────────────────

def calibrate_vfe_threshold(eosc_model: EOSCModel, fault_trials: pd.DataFrame) -> float:
    rca = RootCauseAnalyzer(eosc_model)
    vfe_computer = VFEComputer()

    safe_vfes, unsafe_vfes = [], []
    # Use the first ~50 trials of each fault class for calibration; rest for evaluation
    cal_rows = []
    for f in ["HDF", "PWF", "OSF"]:
        cal_rows.extend(
            fault_trials[fault_trials["fault_label"] == f].head(40).to_dict(orient="records")
        )
    for row in cal_rows:
        obs = dict(row)
        obs["slo_violated"] = True
        obs_bn = discretize_real_observation(obs)
        diag = diagnose_slo_violation(rca, obs_bn, top_k=3, impact_calibration=0.42)
        if not diag["root_causes"]:
            continue
        action = diag["candidate_action"]
        vfe = vfe_computer.compute_vfe(eosc_model, obs_bn, action)
        correct_set = FAULT_TO_CORRECT_ACTIONS[row["fault_label"]]
        (safe_vfes if action in correct_set else unsafe_vfes).append(vfe)

    if not safe_vfes:
        return 1.0
    max_safe = max(safe_vfes)
    if unsafe_vfes and min(unsafe_vfes) > max_safe:
        gap_lo, gap_hi = max_safe, min(unsafe_vfes)
        F_th = gap_lo + 0.3 * (gap_hi - gap_lo)
        print(f"  Auto-calibrated F_th = {F_th:.3f}  (GAP found: [{gap_lo:.3f}, {gap_hi:.3f}])")
        print(f"    safe   n={len(safe_vfes)}  range [{min(safe_vfes):.3f}, {max(safe_vfes):.3f}]")
        print(f"    unsafe n={len(unsafe_vfes)} range [{min(unsafe_vfes):.3f}, {max(unsafe_vfes):.3f}]")
        return F_th
    all_vfes = safe_vfes + (unsafe_vfes or [])
    F_th = max(all_vfes) + 1.0
    print(f"  Auto-calibrated F_th = {F_th:.3f}  (NO GAP)")
    print(f"    safe   n={len(safe_vfes)}  range [{min(safe_vfes):.3f}, {max(safe_vfes):.3f}]")
    if unsafe_vfes:
        print(f"    unsafe n={len(unsafe_vfes)} range [{min(unsafe_vfes):.3f}, {max(unsafe_vfes):.3f}]")
    return F_th


# ─── Experiment runner ─────────────────────────────────────────────────────

def run():
    out_dir = Path("/Users/suvidesilva/Downloads/ai_agnt/experiments/results")
    out_dir.mkdir(parents=True, exist_ok=True)

    logger.remove()
    logger.add(lambda m: None)

    random.seed(42)
    print()
    print("=" * 80)
    print("REAL DATA — AI4I 2020 Predictive Maintenance Dataset")
    print("=" * 80)

    training_rows, fault_trials, all_rows = load_real_dataset()
    print(f"  Training rows:    {len(training_rows)} (1000 healthy + {len(fault_trials)} faulty)")
    print(f"  Test trials:      {len(fault_trials)} clean single-fault rows")
    for f in ["HDF", "PWF", "OSF"]:
        n = len(fault_trials[fault_trials["fault_label"] == f])
        print(f"    {f}: {n}")

    eosc_model = fit_real_data_bn(training_rows)
    print(f"  BN fitted: {len(REAL_DATA_EDGES)} edges, {len(training_rows)} rows")

    print()
    F_th = calibrate_vfe_threshold(eosc_model, fault_trials)
    print()

    # Evaluate on ALL fault trials (calibration set + held-out)
    agents = {
        "real_rule_based":  RealRuleBasedAgent(),
        "real_aif_no_gate": RealAIFNoGateAgent(eosc_model),
        "real_aurora":      create_real_aurora_agent(eosc_model, vfe_threshold=F_th),
    }

    results = {}
    for name, agent in agents.items():
        per_fault = {f: Counter() for f in ["HDF", "PWF", "OSF"]}
        all_trials = []
        gate1_fires = 0
        gate2_fires = 0
        for _, row in fault_trials.iterrows():
            fault = row["fault_label"]
            obs = dict(row)
            obs["slo_violated"] = True
            r = agent.process_observation(obs)
            outcome = classify_outcome(fault, r)
            per_fault[fault][outcome] += 1
            if r.get("gate1_fired"): gate1_fires += 1
            if r.get("gate2_fired"): gate2_fires += 1
            all_trials.append({
                "trial_id": int(row["UDI"]), "fault_type": fault,
                "action_outcome": outcome,
                "action_taken": r.get("action_taken"),
                "abstention": r.get("abstained"),
                "destructive_action": outcome == "destructive",
                "certainty_score": r.get("certainty"),
                "vfe_value": r.get("vfe"),
                "root_cause_identified": r.get("root_cause"),
                "gate1_fired": r.get("gate1_fired", False),
                "gate2_fired": r.get("gate2_fired", False),
            })
        results[name] = {
            "per_fault": {f: dict(c) for f, c in per_fault.items()},
            "trials": all_trials,
            "gate1_fires": gate1_fires,
            "gate2_fires": gate2_fires,
        }
        out_path = out_dir / f"{name}_results.json"
        with open(out_path, "w") as f:
            json.dump({"trials": all_trials, "num_trials": len(all_trials)}, f)
        print(f"  Wrote {out_path.name}")

    print()
    print("=" * 80)
    print(f"REAL DATA RESULTS  (F_th = {F_th:.2f}, tau_base = 0.70)")
    print("=" * 80)
    print(f"{'Agent':<24} {'Correct':<12} {'Abstain':<12} {'Destructive':<12}  (n={len(fault_trials)})")
    print("-" * 80)
    for name, data in results.items():
        agg = Counter()
        for f_counter in data["per_fault"].values():
            agg.update(f_counter)
        n = sum(agg.values())
        print(f"{name:<24} {100*agg['correct']/n:6.2f}%      "
              f"{100*agg['abstained']/n:6.2f}%      "
              f"{100*agg['destructive']/n:6.2f}%")

    print()
    print("AURORA gate firings:")
    print(f"  Gate 1 (certainty): {results['real_aurora']['gate1_fires']}")
    print(f"  Gate 2 (VFE):       {results['real_aurora']['gate2_fires']}")

    print()
    print("Per-fault breakdown:")
    for name, data in results.items():
        print(f"\n  === {name} ===")
        for fault in ["HDF", "PWF", "OSF"]:
            c = data["per_fault"].get(fault, {})
            n = sum(c.values())
            if n == 0:
                continue
            row = "  ".join(f"{k}={100*v/n:5.2f}%" for k, v in sorted(c.items()))
            print(f"    {fault} (n={n}):  {row}")

    return results, F_th


if __name__ == "__main__":
    run()
